export function renderSignatureBlock(
  roles: Array<{ role: string; hint?: string }> = [
    { role: 'Authorized Signatory', hint: 'Name / Designation / Date' },
    { role: 'Countersignature (if required)', hint: 'CSR Committee Chair / CFO / Partner' },
  ]
): string {
  return `
    <div class="section">
      <div class="section-title">Authorization</div>
      <p class="section-intro">Wet-ink or digital signatures to be affixed by the organization after review. GRAM does not apply statutory signatures.</p>
      <div class="signature-grid">
        ${roles
          .map(
            (item) => `
          <div class="signature-box">
            <div class="role">${escapeHtml(item.role)}</div>
            <div class="hint">${escapeHtml(item.hint || 'Name / Designation / Date')}</div>
          </div>`
          )
          .join('')}
      </div>
    </div>
  `
}

