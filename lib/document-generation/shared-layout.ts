export function renderGapsSection(gaps: string[]): string {
  if (!gaps.length) return ''
  return `
    <div class="section">
      <div class="section-title">Data Completeness Notes</div>
      <div class="gaps">
        The following fields were missing or incomplete on the platform. Complete them before board / MCA / funder submission.
        <ul>${gaps.map((gap) => `<li>${escapeHtml(gap)}</li>`).join('')}</ul>
      </div>
    </div>
  `
}
