export function readNgoTextField(value: unknown): string {
  return String(value || '').trim();
}

export function readNgoNumberField(value: unknown): string {
  return readNgoTextField(value).replace(/[^\d]/g, '');
}

export function toIsoExpiryDate(year: number, month: number, day: number): string | null {
  if (year < 1900 || month < 1 || month > 12 || day < 1 || day > 31) return null;
  const date = new Date(Date.UTC(year, month - 1, day));
  if (
    date.getUTCFullYear() !== year ||
    date.getUTCMonth() !== month - 1 ||
    date.getUTCDate() !== day
  ) {
    return null;
  }
  return `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
}
